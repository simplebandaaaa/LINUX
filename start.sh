#!/bin/bash

set -e

# ============================================================
# RUNTIME DIRECTORIES
# ============================================================

mkdir -p /run/dbus
mkdir -p /run/xrdp

# Remove old X11 sockets
rm -rf /tmp/.X11-unix/* 2>/dev/null || true

# ============================================================
# DBUS
# ============================================================

dbus-daemon --system --fork 2>/dev/null || true

# ============================================================
# XRDP SESSION MANAGER
# ============================================================

/usr/sbin/xrdp-sesman

# ============================================================
# XRDP
# ============================================================

exec /usr/sbin/xrdp --nodaemon
